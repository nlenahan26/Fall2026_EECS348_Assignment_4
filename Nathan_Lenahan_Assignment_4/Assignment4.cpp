// The following SudokuSolver class is from the original code generated by Claude
// It uses recursive backtracking to find and store every solution to a puzzle
class SudokuSolver { // Starts the SudokuSolver class
public: // Makes the following constructor and method accessible outside the class

    // The following SudokuSolver constructor is from the original code generated by Claude
    // It creates a working copy of the provided puzzle
    explicit SudokuSolver(const Board& puzzle) : board(puzzle) {} // Copies the puzzle into board and prevents implicit conversion from Board to SudokuSolver

    // The following solveAll method is from the original code generated by Claude
    // It clears previous solutions, checks the starting clues, and starts the search
    const vector<Board>& solveAll() { // Starts the method that returns a read-only reference to the stored solutions

        solutions.clear(); // Removes any solutions stored by a previous call
        if (board.givensAreConsistent()) // Checks whether the starting clues have no row, column, or block conflicts
            search(); // Starts the recursive search only if the clues pass validation
        return solutions; // Returns access to the solution vector without copying it
    } // Ends the solveAll method

private: // Restricts access to the following data and helper method to SudokuSolver
    Board board; // Stores the working board that the recursive search modifies
    vector<Board> solutions; // Stores a copy of every completed solution found

    // The following search method is from the original code generated by Claude
    // It tries allowed digits recursively, saves completed boards, and undoes placements
    void search() { // Starts the recursive search for all solutions

        int row, col; // Declares variables that receive the next empty cell's position
        if (!board.findEmpty(row, col)) { // Checks the base case where no empty cells remain
            solutions.push_back(board); // Copies the completed board into the solution vector
            return; // Ends this recursive call after saving the solution
        } // Ends the completed-board check

        for (int v = 1; v <= 9; v++) { // Tries each candidate digit from 1 through 9
            if (board.canPlace(row, col, v)) { // Checks whether the candidate has no row, column, or block conflicts
                board.set(row, col, v); // Places the candidate in the empty cell
                search(); // Recursively explores the board with this additional cell filled
                board.set(row, col, 0); // Removes the attempted digit so another candidate can be tried
            } // Ends the allowed-placement check
        } // Ends the candidate loop
    } // Ends the search method
}; // Ends the SudokuSolver class

